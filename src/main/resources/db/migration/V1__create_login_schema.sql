-- ============================================================
-- ÁP DỤNG APPEND-ONLY CHO SỔ CÁI CÔNG NỢ (Production hardening)
-- ============================================================
CREATE OR REPLACE FUNCTION fn_block_ledger_mutation()
RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'customer_ledger_entries là append-only: không được UPDATE/DELETE, chỉ được thêm bút toán mới';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_block_ledger_update
    BEFORE UPDATE ON customer_ledger_entries
    FOR EACH ROW EXECUTE FUNCTION fn_block_ledger_mutation();

CREATE TRIGGER trg_block_ledger_delete
    BEFORE DELETE ON customer_ledger_entries
    FOR EACH ROW EXECUTE FUNCTION fn_block_ledger_mutation();