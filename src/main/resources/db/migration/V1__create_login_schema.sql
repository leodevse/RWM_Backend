CREATE TABLE users (
                       id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
                       login_identifier    text NOT NULL,
                       password_hash       text NOT NULL,
                       full_name           text,
                       role                text NOT NULL,
                       account_status      text NOT NULL DEFAULT 'active',
                       last_login_at       timestamptz,
                       created_at          timestamptz NOT NULL DEFAULT now(),
                       updated_at          timestamptz NOT NULL DEFAULT now(),
                       CONSTRAINT uq_users_login_identifier UNIQUE (login_identifier),
                       CONSTRAINT chk_users_role CHECK (role IN ('owner','salesperson','cashier')),
                       CONSTRAINT chk_users_account_status CHECK (account_status IN ('active','locked','disabled'))
);
COMMENT ON TABLE users IS 'Người dùng hệ thống: chủ / bán hàng / thu ngân';

CREATE TABLE login_audit_logs (
                                  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
                                  user_id             uuid,
                                  login_identifier    text NOT NULL,
