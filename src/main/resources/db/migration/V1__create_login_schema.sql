                                      failure_reason IS NULL
                                          OR failure_reason IN ('invalid_password','account_locked','account_disabled','unknown_identifier','other')
                                      )
);
COMMENT ON TABLE login_audit_logs IS 'Audit trail đăng nhập, append-only';

